package dev.zeralius.clowder.execution.domain;

import static org.assertj.core.api.Assertions.assertThat;

import dev.zeralius.clowder.planning.plan.api.PlanStopResponse;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Random;
import org.junit.jupiter.api.Test;

/**
 * The projector is a pure function over DTOs, so this is a unit test with nothing to start.
 *
 * <p>Three stops planned to depart at 10:00, 11:00 and 12:00. Every assertion below is about what the
 * fold does with events that arrive in the wrong order, twice, or not at all — which is the normal
 * case, not the exceptional one.
 */
class PlanProjectorTest {

    private static final Instant NINE = Instant.parse("2026-01-05T09:00:00Z");

    private final PlanProjector projector = new PlanProjector();

    private static PlanStopResponse stop(long id, int sequence, long consignmentId, Instant plannedDeparture) {
        return new PlanStopResponse(
                id,
                sequence,
                consignmentId,
                "REF-" + consignmentId,
                "Somewhere " + consignmentId,
                plannedDeparture.minusSeconds(900),
                plannedDeparture.minusSeconds(900),
                plannedDeparture,
                0,
                0L,
                0L);
    }

    private static final List<PlanStopResponse> STOPS = List.of(
            stop(10L, 0, 100L, NINE.plusSeconds(3600)),
            stop(20L, 1, 200L, NINE.plusSeconds(7200)),
            stop(30L, 2, 300L, NINE.plusSeconds(10_800)));

    private static DriverEvent event(long id, Long stopId, DriverEventType type, int minutesAfterNine) {
        return event(id, stopId, type, minutesAfterNine, null);
    }

    /** Ids are normally database-generated; here they stand for arrival order within one timestamp. */
    private static DriverEvent event(
            long id, Long stopId, DriverEventType type, int minutesAfterNine, FailureReason reason) {
        final var event = new DriverEvent(
                "key-" + id, 1L, stopId, type, NINE.plusSeconds(minutesAfterNine * 60L), null, null, reason);
        setId(event, id);
        return event;
    }

    /**
     * The id is generated by the database, and the projector uses it only to break timestamp ties. A
     * setter on the entity would be API erosion for the sake of a test, so the test reaches in instead.
     */
    private static void setId(DriverEvent event, long id) {
        try {
            final var field = DriverEvent.class.getDeclaredField("id");
            field.setAccessible(true);
            field.set(event, id);
        } catch (ReflectiveOperationException e) {
            throw new IllegalStateException(e);
        }
    }

    @Test
    void anEmptyLogLeavesEverythingPending() {
        final var projection = projector.project(1L, STOPS, List.of());

        assertThat(projection.completed()).isZero();
        assertThat(projection.remaining()).isEqualTo(3);
        assertThat(projection.currentDelayMinutes()).isZero();
        assertThat(projection.lastKnownDeparture()).isNull();
        assertThat(projection.stops()).allMatch(stop -> stop.status() == StopStatus.PENDING);
    }

    @Test
    void stopsComeBackInPlanSequenceWhateverOrderTheEventsArrivedIn() {
        final var projection = projector.project(
                1L,
                List.of(STOPS.get(2), STOPS.get(0), STOPS.get(1)),
                List.of(event(1L, 30L, DriverEventType.DELIVERED, 180)));

        assertThat(projection.stops()).extracting(StopState::planStopId).containsExactly(10L, 20L, 30L);
    }

    /** The case the whole design is for: a tunnel, then six events at once in the wrong order. */
    @Test
    void aDeliveredArrivingBeforeItsArrivedStillEndsDelivered() {
        final var projection = projector.project(
                1L,
                STOPS,
                List.of(event(2L, 10L, DriverEventType.DELIVERED, 58), event(1L, 10L, DriverEventType.ARRIVED, 50)));

        final var first = projection.stops().getFirst();
        assertThat(first.status()).isEqualTo(StopStatus.DELIVERED);
        assertThat(first.actualArrival()).isEqualTo(NINE.plusSeconds(50 * 60L));
        assertThat(first.actualDeparture()).isEqualTo(NINE.plusSeconds(58 * 60L));
    }

    /** Precedence, not last-write-wins. A late ARRIVED must not undo a DELIVERED. */
    @Test
    void anArrivedThatTurnsUpAfterADeliveredIsIgnored() {
        final var projection = projector.project(
                1L,
                STOPS,
                List.of(event(1L, 10L, DriverEventType.DELIVERED, 50), event(2L, 10L, DriverEventType.ARRIVED, 90)));

        assertThat(projection.stops().getFirst().status()).isEqualTo(StopStatus.DELIVERED);
    }

    @Test
    void theFoldDoesNotDependOnTheOrderTheEventsAreHandedOver() {
        final var log = new ArrayList<>(List.of(
                event(1L, null, DriverEventType.DEPARTED_DEPOT, 10),
                event(2L, 10L, DriverEventType.ARRIVED, 45),
                event(3L, 10L, DriverEventType.DELIVERED, 58),
                event(4L, 20L, DriverEventType.ARRIVED, 100),
                event(5L, 20L, DriverEventType.FAILED, 110, FailureReason.CUSTOMER_ABSENT),
                event(6L, 30L, DriverEventType.ARRIVED, 170)));

        final var inOrder = projector.project(1L, STOPS, log);

        final var shuffled = new ArrayList<>(log);
        Collections.shuffle(shuffled, new Random(20260105L));

        assertThat(projector.project(1L, STOPS, shuffled)).isEqualTo(inOrder);
    }

    @Test
    void aFailedStopIsCompleteAndKeepsItsReason() {
        final var projection = projector.project(
                1L, STOPS, List.of(event(1L, 20L, DriverEventType.FAILED, 110, FailureReason.REFUSED)));

        final var second = projection.stops().get(1);
        assertThat(second.status()).isEqualTo(StopStatus.FAILED);
        assertThat(second.failureReason()).isEqualTo(FailureReason.REFUSED);
        assertThat(projection.completed()).isEqualTo(1);
        assertThat(projection.remaining()).isEqualTo(2);
    }

    /** Stop 20 was planned to depart at 11:00 and actually departed at 11:25. */
    @Test
    void delayIsMeasuredAgainstThePlannedDepartureOfTheLastCompletedStop() {
        final var projection = projector.project(
                1L,
                STOPS,
                List.of(event(1L, 10L, DriverEventType.DELIVERED, 55), event(2L, 20L, DriverEventType.DELIVERED, 145)));

        assertThat(projection.currentDelayMinutes()).isEqualTo(25);
        assertThat(projection.lastCompletedStopId()).isEqualTo(20L);
        assertThat(projection.lastKnownDeparture()).isEqualTo(NINE.plusSeconds(145 * 60L));
    }

    /** Running early is the same calculation with the other sign, not a special case. */
    @Test
    void runningEarlyIsANegativeDelay() {
        final var projection = projector.project(1L, STOPS, List.of(event(1L, 10L, DriverEventType.DELIVERED, 50)));

        assertThat(projection.currentDelayMinutes()).isEqualTo(-10);
    }

    @Test
    void departedDepotMovesTheTimelineWithoutTouchingAnyStop() {
        final var projection =
                projector.project(1L, STOPS, List.of(event(1L, null, DriverEventType.DEPARTED_DEPOT, 5)));

        assertThat(projection.lastKnownDeparture()).isEqualTo(NINE.plusSeconds(5 * 60L));
        assertThat(projection.lastCompletedStopId()).isNull();
        assertThat(projection.stops()).allMatch(stop -> stop.status() == StopStatus.PENDING);
    }

    /** A bad stop reference must not wedge the rest of the day. */
    @Test
    void anEventForAStopThatIsNotOnThisPlanIsIgnored() {
        final var projection = projector.project(1L, STOPS, List.of(event(1L, 999L, DriverEventType.DELIVERED, 60)));

        assertThat(projection.completed()).isZero();
        assertThat(projection.stops()).hasSize(3);
    }

    @Test
    void remainingStopsExcludesTheCompletedOnes() {
        final var projection = projector.project(
                1L,
                STOPS,
                List.of(
                        event(1L, 10L, DriverEventType.DELIVERED, 55),
                        event(2L, 20L, DriverEventType.FAILED, 110, FailureReason.ACCESS_DENIED)));

        assertThat(projection.remainingStops())
                .extracting(StopState::planStopId)
                .containsExactly(30L);
        assertThat(projection.isFinished()).isFalse();
    }
}
